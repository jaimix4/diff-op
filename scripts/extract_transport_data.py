# ==========================================
# 2. GEOMETRY MAPPING
# ==========================================
def get_mapping_factor(filename):
    with open(filename, "r") as f:
        data = geqdsk.read(f)
        
    r_arr = np.linspace(data.rleft, data.rleft + data.rdim, data.nx)
    z_arr = np.linspace(data.zmid - data.zdim / 2, data.zmid + data.zdim / 2, data.ny)
    psi_2d_arr = data.psi

    z_axis_idx = np.argmin(np.abs(z_arr - data.zmagx))
    psi_midplane = psi_2d_arr[:, z_axis_idx]

    outboard_mask = r_arr >= data.rmagx
    r_outboard = r_arr[outboard_mask]
    psi_outboard = psi_midplane[outboard_mask]

    rho_pol_outboard = np.sqrt((psi_outboard - data.simagx) / (data.sibdry - data.simagx))
    drho_dR_outboard = np.gradient(rho_pol_outboard, r_outboard)
    return rho_pol_outboard, drho_dR_outboard

