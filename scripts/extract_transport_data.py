    data = np.loadtxt(io.StringIO(raw_string.strip()), delimiter=',')
    data = data[np.argsort(data[:, 0])]
    rho, unique_idx = np.unique(data[:, 0], return_index=True)
    return rho, data[unique_idx, 1]

